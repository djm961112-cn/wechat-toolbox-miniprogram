const assert = require('node:assert/strict')
const { normalizeCode, rulePayload } = require('../utils/stocks')
assert.equal(normalizeCode('600519'), 'SH.600519')
assert.equal(normalizeCode('000001'), 'SZ.000001')
assert.equal(normalizeCode('sz.300750'), 'SZ.300750')
assert.throws(() => normalizeCode('US.AAPL'))
assert.throws(() => rulePayload({ metric: 'PRICE', threshold: '0' }))
assert.throws(() => rulePayload({ metric: 'DAY_CHANGE_PCT', threshold: 'oops' }))
const rule = rulePayload({ symbol: 'SZ.000001', metric: 'DAY_CHANGE_PCT', comparison: 'LTE', threshold: '-3', repeatMode: 'DAILY_ONCE', enabled: true }, { id: 5, version: 3 })
assert.equal(rule.threshold, -3)
assert.equal(rule.expectedVersion, 3)
assert.equal(rule.matchCurrent, false)
console.log('PASS: stock code normalization and rule threshold/version contract')
