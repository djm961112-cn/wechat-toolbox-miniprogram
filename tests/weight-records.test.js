const assert = require('assert')
const memory = new Map()
global.wx = { getStorageSync: (key) => memory.get(key), setStorageSync: (key, value) => memory.set(key, JSON.parse(JSON.stringify(value))) }
const { normalizeWeight, readRecords, saveRecord, periodRows, chartModel } = require('../utils/weight-records')

assert.strictEqual(normalizeWeight('65.25'), 65.25)
assert.throws(() => normalizeWeight(''))
assert.throws(() => normalizeWeight('19.9'))
assert.throws(() => normalizeWeight('65.123'))

const first = new Date(2026, 9, 10, 8).getTime()
const laterSameDay = new Date(2026, 9, 10, 20).getTime()
const latest = new Date(2026, 9, 14, 8).getTime()
saveRecord('66', first)
saveRecord('65.8', laterSameDay)
saveRecord('65.2', latest)
assert.strictEqual(readRecords().length, 3)
const week = periodRows(readRecords(), 'week', new Date(2026, 9, 14, 12).getTime())
assert.deepStrictEqual(week.map((item) => item.weight), [65.8, 65.2])
const year = periodRows(readRecords(), 'year', new Date(2026, 9, 14, 12).getTime())
assert.strictEqual(year.length, 1)
assert.strictEqual(year[0].weight, 65.67)
const chart = chartModel(week)
assert.strictEqual(chart.points.length, 2)
assert.strictEqual(chart.segments.length, 1)
assert.strictEqual(chart.change, '-0.6')
assert.ok(chart.points.every((point) => point.showLabel && point.showValue))
console.log('PASS: weight validation, local persistence, period grouping and chart model')
